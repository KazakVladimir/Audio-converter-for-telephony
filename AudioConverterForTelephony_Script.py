from pydub import AudioSegment

def convert_audio_to_8khz_100kb_wav(input_filepath, output_filepath_base="converted_audio"):
    """
    Преобразует аудиофайл в формат WAV с частотой дискретизации 8000 Гц,
    моноканал и пытается сохранить размер файла менее 100 КБ.
    Определяет приоритет телефонных кодеков (u-law, A-law), затем других форматов PCM,
    и, наконец, при необходимости выполняет усечение.

    Args:
        input_filepath (str): Путь к входному аудиофайлу.
        output_filepath_base (str): Базовое имя для выходного WAV-файла.
                                    Суффиксы будут добавлены в зависимости от этапов преобразования.

    Returns:
        str: Путь к сгенерированному WAV-файлу или нет, если преобразование завершилось неудачно.
    """
    MAX_SIZE_BYTES = 100 * 1024  # 100 KB

    try:
        if not os.path.exists(input_filepath):
            print(f"Ошибка: Входной файл не найден по адресу '{input_filepath}'")
            return None

        # Загрузите аудиофайл
        audio = AudioSegment.from_file(input_filepath)

        # Установите частоту дискретизации на 8000 Гц и преобразуйте в моно (одноканальный)
        audio = audio.set_frame_rate(8000).set_channels(1)

        # --- Попытка 1: G.711 u-law WAV (8 кГц, 8 бит, моно) --- Стандарт телефонии
        # Скорость передачи данных: 8000 Hz * 1 channel * 1 byte/sample = 8000 bytes/sec
        # Максимальная продолжительность для 100KB: 102400 / 8000 = 12.8 seconds
        output_path_mulaw = f"{output_filepath_base}_mulaw.wav"
        print(f"Попытка преобразования WAV в u-образный формат G.711 для '{input_filepath}'...")
        audio.export(output_path_mulaw, format="wav", codec="pcm_mulaw")

        if os.path.exists(output_path_mulaw) and os.path.getsize(output_path_mulaw) <= MAX_SIZE_BYTES:
            final_size_kb = os.path.getsize(output_path_mulaw) / 1024
            print(f"Успешно преобразован в G.711 u-law WAV: {output_path_mulaw} (Размер: {final_size_kb:.2f} KB)")
            return output_path_mulaw
        elif os.path.exists(output_path_mulaw):
            print(f"G.711 u-образный размер WAV ({os.path.getsize(output_path_mulaw) / 1024:.2f} KB) exceeds 100 KB. Trying A-law.")
            os.remove(output_path_mulaw) # Очищаем
        else:
            print("G.711 u-law не удалось выполнить экспорт в формате WAV или файл не был создан. Пытаюсь использовать A-law.")

        # --- Попытка 2: G.711 A-law WAV (8 кГц, 8 бит, моно) --- Еще один распространенный стандарт телефонии
        # Скорость передачи данных: 8000 Hz * 1 channel * 1 byte/sample = 8000 bytes/sec
        # Максимальная продолжительность для 100KB: 102400 / 8000 = 12.8 seconds
        output_path_alaw = f"{output_filepath_base}_alaw.wav"
        print(f"Попытка преобразования WAV в формат G.711 A-law...")
        audio.export(output_path_alaw, format="wav", codec="pcm_alaw")

        if os.path.exists(output_path_alaw) and os.path.getsize(output_path_alaw) <= MAX_SIZE_BYTES:
            final_size_kb = os.path.getsize(output_path_alaw) / 1024
            print(f"Успешно преобразован в G.711 A-law WAV: {output_path_alaw} (Размер: {final_size_kb:.2f} KB)")
            return output_path_alaw
        elif os.path.exists(output_path_alaw):
            print(f"G.711 A-law WAV размер ({os.path.getsize(output_path_alaw) / 1024:.2f} KB) exceeds 100 KB. Trying 8-bit PCM.")
            os.remove(output_path_alaw) # Clean up
        else:
            print("G.711 A-law WAV export failed or file not created. Trying 8-bit PCM.")

        # --- Attempt 3: 8-bit PCM WAV (8kHz, 8-bit, mono) --- General purpose
        # Data rate: 8000 Hz * 1 channel * 1 byte/sample = 8000 bytes/sec
        output_path_8bit = f"{output_filepath_base}_pcm8.wav"
        print(f"Attempting 8-bit PCM WAV conversion...")
        audio.export(output_path_8bit, format="wav", codec="pcm_u8")

        if os.path.exists(output_path_8bit) and os.path.getsize(output_path_8bit) <= MAX_SIZE_BYTES:
            final_size_kb = os.path.getsize(output_path_8bit) / 1024
            print(f"Successfully converted to 8-bit PCM WAV: {output_path_8bit} (Size: {final_size_kb:.2f} KB)")
            return output_path_8bit
        elif os.path.exists(output_path_8bit):
            print(f"8-bit PCM WAV size ({os.path.getsize(output_path_8bit) / 1024:.2f} KB) exceeds 100 KB. Trying 16-bit PCM.")
            os.remove(output_path_8bit) # Clean up
        else:
            print("8-bit PCM WAV export failed or file not created. Trying 16-bit PCM.")

        # --- Attempt 4: 16-bit PCM WAV (8kHz, 16-bit, mono) --- Higher quality, larger size
        # Data rate: 8000 Hz * 1 channel * 2 bytes/sample = 16000 bytes/sec
        output_path_16bit = f"{output_filepath_base}_pcm16.wav"
        print(f"Attempting 16-bit PCM WAV conversion...")
        audio.export(output_path_16bit, format="wav", codec="pcm_s16le")

        if os.path.exists(output_path_16bit) and os.path.getsize(output_path_16bit) <= MAX_SIZE_BYTES:
            final_size_kb = os.path.getsize(output_path_16bit) / 1024
            print(f"Successfully converted to 16-bit PCM WAV: {output_path_16bit} (Size: {final_size_kb:.2f} KB)")
            return output_path_16bit
        elif os.path.exists(output_path_16bit):
            print(f"16-bit PCM WAV size ({os.path.getsize(output_path_16bit) / 1024:.2f} KB) exceeds 100 KB. Proceeding to truncation with u-law.")
            os.remove(output_path_16bit) # Clean up
        else:
            print("16-bit PCM WAV export failed or file not created. Proceeding to truncation with u-law.")

        # --- Attempt 5: Truncate audio (using u-law) if still too large --- (Fallback if previous attempts fail)
        # Calculate maximum duration for 100KB at 8000Hz, 8-bit mono (u-law is effectively 8-bit)
        # 8000 bytes/second
        max_duration_seconds = MAX_SIZE_BYTES / 8000.0
        max_duration_ms = math.floor(max_duration_seconds * 1000) # Floor to avoid exceeding

        if len(audio) > max_duration_ms:
            print(f"Audio is too long for 100KB limit with any codec. Truncating to {max_duration_ms / 1000:.2f} seconds and exporting as G.711 u-law.")
            truncated_audio = audio[:max_duration_ms]
            output_path_truncated = f"{output_filepath_base}_ulaw_truncated.wav"
            truncated_audio.export(output_path_truncated, format="wav", codec="pcm_mulaw")

            if os.path.exists(output_path_truncated):
                final_size_kb = os.path.getsize(output_path_truncated) / 1024
                print(f"Truncated G.711 u-law WAV saved to: {output_path_truncated} (Size: {final_size_kb:.2f} KB)")
                return output_path_truncated
            else:
                print("Truncated G.711 u-law WAV export failed or file not created.")
        else:
            print(f"Audio duration ({len(audio) / 1000:.2f}s) is within 100KB limits, but previous codec attempts failed or exceeded size. This might be due to WAV header overhead or other specific requirements not met. No further truncation possible.")

    except FileNotFoundError:
        print(f"Error: The input file '{input_filepath}' was not found. Please ensure it's uploaded or the path is correct.")
    except Exception as e:
        print(f"An error occurred during audio conversion: {e}")

    print("Could not convert audio to 8000Hz WAV and under 100KB with compatible codecs.")
    return None

